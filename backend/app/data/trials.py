def _build_generated_trials(base_trials: tuple[Trial, ...], *, target_total: int) -> tuple[Trial, ...]:
    generated: list[Trial] = []
    variants = (
        "biomarker-selected",
        "real-world evidence",
        "dose optimization",
        "quality-of-life",
    )

    for index in range(target_total - len(base_trials)):
        source = base_trials[index % len(base_trials)]
        variant = variants[index % len(variants)]
        sequence = 2001 + index
        month = (index % 12) + 1
        day = (index % 27) + 1

        generated.append(
            Trial(
                id=f"NCT-{sequence}",
                title=f"{source.title} ({variant} cohort {index + 1})",
                condition=source.condition,
                sponsor=f"{source.sponsor} - Extension Program",
                phase=source.phase,
                status=source.status,
                summary=f"{source.summary} This generated demo record represents a {variant} extension cohort.",
                intervention=source.intervention,
                eligibility=source.eligibility
                + (
                    "Able to comply with study visits",
                    f"Eligible for the {variant} cohort",
                ),
                locations=source.locations,
                last_updated=f"2024-{month:02d}-{day:02d}",
                contact_email=f"trial-{sequence}@example.test",
                source_url=f"https://clinicaltrials.example.test/NCT-{sequence}",
            )
        )

    return tuple(generated)


TRIALS: tuple[Trial, ...] = _BASE_TRIALS + _build_generated_trials(_BASE_TRIALS, target_total=100)
